/*
    Multi Dimensional:
    
    A multi-dimensional array is an array that contains 
    other arrays as its elements. 
    
    Multi-dimensional arrays can be defined using the 
    same notation as one-dimensional arrays, 
    but with nested square brackets.
*/

const arr1D: number[] = [2, 5, 6];
const arr2D: number[][] = [[2, 5, 6]];
const arr3D: number[][][] = [[[2, 5, 6]]];

console.log(arr1D);
console.log(arr2D);
console.log(arr3D);
